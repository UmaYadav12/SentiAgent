"""
augment_dataset.py

LLM-driven semantic augmentation for creating Neutral and Mixed sentiment
samples from sentiment datasets.

Expected input CSV columns:
    text, label, dataset

The script generates new Neutral and Mixed samples for each dataset and saves
them to a CSV file. Original rows are not modified.

Model:
    meta-llama/Llama-3.1-8B-Instruct

Requirements:
    pip install pandas tqdm torch transformers accelerate sentencepiece
    huggingface-cli login
"""

import os
import re
import argparse
from pathlib import Path

import pandas as pd
import torch
from tqdm.auto import tqdm
from transformers import AutoTokenizer, AutoModelForCausalLM


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

MODEL_NAME = os.getenv(
    "MODEL_NAME",
    "meta-llama/Llama-3.1-8B-Instruct"
)

DEFAULT_INPUT = "combined_dataset.csv"
DEFAULT_OUTPUT = "augmented_dataset.csv"

TARGET_CLASSES = ["Neutral", "Mixed"]

# Number of generated samples PER target class PER dataset.
DEFAULT_N_PER_CLASS = 10

MAX_NEW_TOKENS = 80
TEMPERATURE = 0.8
TOP_P = 0.90
DO_SAMPLE = True

# Remove generated samples that are suspiciously short.
MIN_TEXT_LENGTH = 10


# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

AUGMENTATION_PROMPT = """
You are generating a sentiment-analysis dataset.

Dataset: {dataset}
Target sentiment class: {target}

Generate ONE original English review/sentence belonging clearly to the
TARGET class.

Rules:
1. Write only the review/sentence.
2. Do not provide explanations, labels, headings, quotation marks, or
   bullet points.
3. Keep the text natural and realistic.
4. Preserve a realistic product/service/topic context.
5. Do not mention that the text was generated by an AI or language model.
6. Do not use the words "Neutral", "Mixed", "Positive", or "Negative" to
   describe the label itself.

Definition of the target class:

Neutral:
The text should be factual, descriptive, or balanced without a clearly
dominant positive or negative sentiment. Avoid strong praise or criticism.

Mixed:
The text should contain both positive and negative sentiment toward the
same product, service, experience, or topic. Both sentiments should be
meaningful rather than merely implied.

Generate exactly one sentence or short review.
""".strip()


# ---------------------------------------------------------------------------
# Model loading
# ---------------------------------------------------------------------------

def get_device():
    """Return the best available device."""
    return "cuda" if torch.cuda.is_available() else "cpu"


def load_model(model_name=MODEL_NAME):
    """
    Load the tokenizer and Llama causal language model.

    The Hugging Face account must have access to the selected model.
    Authentication can be done using:
        huggingface-cli login
    or:
        export HF_TOKEN=...
    """

    print(f"Loading model: {model_name}")

    tokenizer = AutoTokenizer.from_pretrained(
        model_name,
        token=os.getenv("HF_TOKEN"),
    )

    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    if torch.cuda.is_available():
        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            torch_dtype=torch.float16,
            device_map="auto",
            token=os.getenv("HF_TOKEN"),
        )
    else:
        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            torch_dtype=torch.float32,
            token=os.getenv("HF_TOKEN"),
        )
        model.to("cpu")

    model.eval()

    print(f"Device: {get_device()}")
    return tokenizer, model


# ---------------------------------------------------------------------------
# Text generation
# ---------------------------------------------------------------------------

def clean_generated_text(text):
    """Clean model output while preserving the generated sentence."""

    if not isinstance(text, str):
        return ""

    text = text.replace("\n", " ")
    text = text.replace("\r", " ")
    text = re.sub(r"\s+", " ", text).strip()

    # Remove common unwanted prefixes.
    prefixes = [
        "Neutral:",
        "Mixed:",
        "Neutral -",
        "Mixed -",
        "Neutral:",
        "Mixed:",
        "Review:",
        "Sentence:",
    ]

    for prefix in prefixes:
        if text.lower().startswith(prefix.lower()):
            text = text[len(prefix):].strip()

    # Remove surrounding quotation marks.
    text = text.strip("\"'“”‘’ ")

    # If the model produced extra instruction-like text, keep the first
    # sentence where possible.
    if "\n" in text:
        text = text.split("\n")[0].strip()

    return text


def generate_text(prompt, tokenizer, model):
    """Generate one text sample from the LLM."""

    messages = [
        {
            "role": "system",
            "content": (
                "You are a careful dataset-generation assistant. "
                "Follow the requested sentiment definition exactly."
            ),
        },
        {
            "role": "user",
            "content": prompt,
        },
    ]

    formatted_prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )

    inputs = tokenizer(
        formatted_prompt,
        return_tensors="pt",
        truncation=True,
        max_length=1024,
    )

    # Put inputs on the same device as the model.
    if torch.cuda.is_available():
        inputs = {
            key: value.to(model.device)
            for key, value in inputs.items()
        }

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=DO_SAMPLE,
            temperature=TEMPERATURE,
            top_p=TOP_P,
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=tokenizer.eos_token_id,
        )

    # Decode only newly generated tokens.
    input_length = inputs["input_ids"].shape[1]
    generated_tokens = outputs[0][input_length:]

    generated = tokenizer.decode(
        generated_tokens,
        skip_special_tokens=True,
    )

    return clean_generated_text(generated)


# ---------------------------------------------------------------------------
# Automatic quality checks
# ---------------------------------------------------------------------------

def normalize_text(text):
    """Normalize text for duplicate detection."""
    text = str(text).lower().strip()
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"[^\w\s]", "", text)
    return text


def contains_invalid_label_word(text):
    """
    Detect explicit label words that can indicate the model ignored the
    generation instruction.
    """
    text_lower = text.lower()

    # These are checked mainly when they appear as explicit meta-labels.
    patterns = [
        r"\bneutral\s*:",
        r"\bmixed\s*:",
        r"\bpositive\s*:",
        r"\bnegative\s*:",
        r"\btarget\s+class\b",
        r"\bsentiment\s+class\b",
    ]

    return any(re.search(pattern, text_lower) for pattern in patterns)


def passes_basic_quality_checks(
    text,
    target_class,
    existing_texts,
):
    """
    Perform lightweight automatic validation.

    These checks do not replace human annotation. They remove obvious
    failures such as empty text, very short text, duplicates, and
    instruction leakage.
    """

    if not text:
        return False, "empty"

    if len(text) < MIN_TEXT_LENGTH:
        return False, "too_short"

    if contains_invalid_label_word(text):
        return False, "label_leakage"

    normalized = normalize_text(text)

    if not normalized:
        return False, "empty_after_normalization"

    if normalized in existing_texts:
        return False, "duplicate"

    # Very long generations often indicate that the model did not follow
    # the "one sentence/short review" instruction.
    if len(text) > 500:
        return False, "too_long"

    # Require some alphabetic content.
    if not re.search(r"[A-Za-z]", text):
        return False, "no_alphabetic_content"

    return True, "accepted"


# ---------------------------------------------------------------------------
# Dataset augmentation
# ---------------------------------------------------------------------------

def augment_dataset(
    dataset_name,
    tokenizer,
    model,
    n_per_class=DEFAULT_N_PER_CLASS,
    existing_texts=None,
):
    """
    Generate Neutral and Mixed samples for one dataset.

    Parameters
    ----------
    dataset_name : str
        Dataset identifier, e.g. SST-2, IMDB, Sentiment140, Amazon Reviews.

    tokenizer : transformers tokenizer
        Loaded Llama tokenizer.

    model : transformers model
        Loaded Llama model.

    n_per_class : int
        Number of accepted samples required for each target class.

    existing_texts : set
        Normalized texts already present in the dataset. Used for duplicate
        filtering.
    """

    generated_rows = []

    if existing_texts is None:
        existing_texts = set()

    # Track all accepted generated samples as well.
    seen_texts = set(existing_texts)

    for target_class in TARGET_CLASSES:

        print(
            f"\n{dataset_name} -> {target_class}"
        )

        accepted = 0
        attempts = 0

        # Allow extra attempts because some generations may fail quality
        # checks.
        max_attempts = max(n_per_class * 3, n_per_class + 5)

        progress = tqdm(
            total=n_per_class,
            desc=f"{dataset_name}-{target_class}",
        )

        while accepted < n_per_class and attempts < max_attempts:

            attempts += 1

            prompt = AUGMENTATION_PROMPT.format(
                target=target_class,
                dataset=dataset_name,
            )

            try:

                generated = generate_text(
                    prompt,
                    tokenizer,
                    model,
                )

                valid, reason = passes_basic_quality_checks(
                    generated,
                    target_class,
                    seen_texts,
                )

                if not valid:
                    print(
                        f"  Rejected ({reason}): {generated[:100]}"
                    )
                    continue

                normalized = normalize_text(generated)
                seen_texts.add(normalized)

                generated_rows.append(
                    {
                        "text": generated,
                        "binary_label": None,
                        "label": target_class,
                        "dataset": dataset_name,
                        "source": "Llama-3.1-8B-Instruct",
                        "augmentation": True,
                        "augmentation_target": target_class,
                    }
                )

                accepted += 1
                progress.update(1)

            except Exception as e:
                print(
                    f"  Error at attempt {attempts}: {e}"
                )

        progress.close()

        if accepted < n_per_class:
            print(
                f"WARNING: Only {accepted}/{n_per_class} "
                f"accepted samples generated for {dataset_name} "
                f"- {target_class}."
            )

    return pd.DataFrame(generated_rows)


# ---------------------------------------------------------------------------
# Input validation
# ---------------------------------------------------------------------------

def validate_input_dataframe(df):
    """Validate the minimum required input columns."""

    required_columns = ["text", "label", "dataset"]

    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            "Missing required columns: "
            + ", ".join(missing)
            + f"\nAvailable columns: {list(df.columns)}"
        )

    df = df.copy()

    df["text"] = (
        df["text"]
        .fillna("")
        .astype(str)
        .str.strip()
    )

    df = df[df["text"].str.len() >= MIN_TEXT_LENGTH].copy()

    return df


# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------

def run_augmentation(
    input_file,
    output_file,
    n_per_class=DEFAULT_N_PER_CLASS,
    model_name=MODEL_NAME,
):
    """Run augmentation for all datasets in the input CSV."""

    input_path = Path(input_file)
    output_path = Path(output_file)

    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}"
        )

    print(f"Reading: {input_path}")

    original_df = pd.read_csv(input_path)

    original_df = validate_input_dataframe(
        original_df
    )

    print(
        f"Original samples: {len(original_df)}"
    )

    print(
        f"Datasets found: "
        f"{original_df['dataset'].dropna().unique().tolist()}"
    )

    # Load Llama once and reuse it for all datasets.
    tokenizer, model = load_model(model_name)

    augmented_parts = []

    for dataset_name in sorted(
        original_df["dataset"]
        .dropna()
        .unique()
    ):

        dataset_df = original_df[
            original_df["dataset"] == dataset_name
        ].copy()

        existing_texts = set(
            dataset_df["text"]
            .map(normalize_text)
            .tolist()
        )

        generated_df = augment_dataset(
            dataset_name=dataset_name,
            tokenizer=tokenizer,
            model=model,
            n_per_class=n_per_class,
            existing_texts=existing_texts,
        )

        if not generated_df.empty:
            augmented_parts.append(generated_df)

    if augmented_parts:
        generated_df = pd.concat(
            augmented_parts,
            ignore_index=True,
        )
    else:
        generated_df = pd.DataFrame(
            columns=[
                "text",
                "binary_label",
                "label",
                "dataset",
                "source",
                "augmentation",
                "augmentation_target",
            ]
        )

    # Preserve original data and append generated samples.
    original_output = original_df.copy()

    # Add metadata columns to original samples if absent.
    if "source" not in original_output.columns:
        original_output["source"] = "Original"

    if "augmentation" not in original_output.columns:
        original_output["augmentation"] = False

    if "augmentation_target" not in original_output.columns:
        original_output["augmentation_target"] = None

    if "binary_label" not in original_output.columns:
        original_output["binary_label"] = None

    combined_df = pd.concat(
        [
            original_output,
            generated_df,
        ],
        ignore_index=True,
    )

    # Remove exact duplicate rows based on normalized text + dataset.
    combined_df["_normalized_text"] = (
        combined_df["text"]
        .map(normalize_text)
    )

    combined_df = combined_df.drop_duplicates(
        subset=["dataset", "_normalized_text"],
        keep="first",
    )

    combined_df = combined_df.drop(
        columns=["_normalized_text"]
    )

    # Save.
    combined_df.to_csv(
        output_path,
        index=False,
        encoding="utf-8-sig",
    )

    print("\n" + "=" * 70)
    print("AUGMENTATION COMPLETED")
    print("=" * 70)

    print(
        f"Original samples : {len(original_output)}"
    )

    print(
        f"Generated samples: {len(generated_df)}"
    )

    print(
        f"Final samples    : {len(combined_df)}"
    )

    print(
        f"Output file      : {output_path.resolve()}"
    )

    print("\nFinal class distribution:")

    print(
        combined_df["label"]
        .value_counts(dropna=False)
    )

    print("\nDataset-wise class distribution:")

    print(
        pd.crosstab(
            combined_df["dataset"],
            combined_df["label"],
        )
    )

    return combined_df


# ---------------------------------------------------------------------------
# Command-line interface
# ---------------------------------------------------------------------------

def main():

    parser = argparse.ArgumentParser(
        description=(
            "Generate Neutral and Mixed sentiment samples "
            "using Llama 3.1 8B Instruct."
        )
    )

    parser.add_argument(
        "--input",
        default=DEFAULT_INPUT,
        help="Input CSV file.",
    )

    parser.add_argument(
        "--output",
        default=DEFAULT_OUTPUT,
        help="Output CSV file.",
    )

    parser.add_argument(
        "--n-per-class",
        type=int,
        default=DEFAULT_N_PER_CLASS,
        help=(
            "Number of accepted Neutral and Mixed samples "
            "per dataset."
        ),
    )

    parser.add_argument(
        "--model",
        default=MODEL_NAME,
        help="Hugging Face model checkpoint.",
    )

    args = parser.parse_args()

    if args.n_per_class <= 0:
        raise ValueError(
            "--n-per-class must be greater than zero."
        )

    run_augmentation(
        input_file=args.input,
        output_file=args.output,
        n_per_class=args.n_per_class,
        model_name=args.model,
    )


if __name__ == "__main__":
    main()
